    public function normalizePredeploymentStatus(?string $status): string
    {
        $status = trim((string)$status);
        return in_array($status, ['not_submitted', 'submitted', 'approved', 'needs_revision', 'forwarded', 'accepted', 'orientation_scheduled', 'orientation_completed'], true)
            ? $status
            : 'not_submitted';
    }

    public function effectivePredeploymentStatus(int $studentId, ?string $currentStatus = null, ?array $requirements = null): string
    {
        $currentStatus = $this->normalizePredeploymentStatus($currentStatus);
        if (in_array($currentStatus, ['forwarded', 'accepted', 'orientation_scheduled', 'orientation_completed'], true)) {
            return $currentStatus;
        }

        $requirements ??= $this->requirements($studentId);
        $hasRejected = false;
        $allApproved = true;
        foreach ($requirements as $requirement) {
            $hasFile = !empty($requirement['file_path']);
            $status = trim((string)($requirement['status'] ?? 'pending'));
            if ($hasFile && $status === 'rejected') {
                $hasRejected = true;
            }
            if (!$hasFile || $status !== 'approved') {
                $allApproved = false;
            }
        }
        if ($allApproved) {
            return 'approved';
        }
        if ($hasRejected) {
            return 'needs_revision';
        }
        return $currentStatus;
    }

    /**
     * Keep enrollment.predeployment_status aligned once every stage-1 file is coordinator-approved.
     * Uses the raw DB row (byStudent) — detailsByStudent overlays effective status and would
     * skip the write once files are already approved.
     */
    public function syncPredeploymentStatusIfComplete(int $studentId): bool
    {
        $enrollment = (new Enrollment($this->db))->byStudent($studentId);
        if (!$enrollment) {
            return false;
        }
        $current = $this->normalizePredeploymentStatus($enrollment['predeployment_status'] ?? 'not_submitted');
        if (!in_array($current, ['submitted', 'not_submitted'], true)) {
            return false;
        }
        if (!$this->hasCompleteRequirements($studentId) || !$this->hasApprovedRequirements($studentId)) {
            return false;
        }
        (new Enrollment($this->db))->setPredeploymentStatus($studentId, 'approved');

        return true;
    }

    /**
     * Realign predeployment_status after stage-1 requirement definitions change
     * (e.g. removed keys). Does not downgrade advanced pipeline states or approved.
     *
     * @return string|null New status, unchanged status, or null when no enrollment
     */
    public function reconcilePredeploymentAfterRequirementDefChange(int $studentId): ?string
    {
        $enrollment = (new Enrollment($this->db))->byStudent($studentId);
        if (!$enrollment) {
            return null;
        }

        $current = $this->normalizePredeploymentStatus($enrollment['predeployment_status'] ?? 'not_submitted');
        if ($this->isPredeploymentPipelineAdvanced($current)) {
            return $current;
        }
        if (!in_array($current, ['not_submitted', 'needs_revision', 'submitted'], true)) {
            return $current;
        }

        if ($this->hasApprovedRequirements($studentId)) {
            $next = 'approved';
        } elseif ($this->hasRejectedRequirements($studentId)) {
            $next = 'needs_revision';
        } elseif ($this->hasCompleteRequirements($studentId)) {
            $next = 'submitted';
        } else {
            $next = 'not_submitted';
        }

        if ($next !== $current) {
            (new Enrollment($this->db))->setPredeploymentStatus($studentId, $next);
        }

        return $next;
    }

    /**
     * @return array{scanned:int, updated:int, unchanged:int}
     */
    public function reconcileAllPredeploymentAfterRequirementDefChange(): array
    {
        $rows = $this->db->query(
            'SELECT student_id, predeployment_status FROM ojt_enrollments
             WHERE predeployment_status IN ("not_submitted", "needs_revision", "submitted")'
        )->fetchAll();

        $scanned = 0;
        $updated = 0;
        $unchanged = 0;
        foreach ($rows as $row) {
            $scanned++;
            $studentId = (int)$row['student_id'];
            $before = $this->normalizePredeploymentStatus($row['predeployment_status'] ?? 'not_submitted');
            $after = $this->reconcilePredeploymentAfterRequirementDefChange($studentId);
            if ($after !== null && $after !== $before) {
                $updated++;
            } else {
                $unchanged++;
            }
        }

        return ['scanned' => $scanned, 'updated' => $updated, 'unchanged' => $unchanged];
    }

